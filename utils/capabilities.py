_CAPABILITY_PATTERNS = (
    r"\bчто\s+ты\s+умеешь\b", r"\bчто\s+ты\s+можешь\b",
    r"\bчем\s+ты\s+можешь\s+помочь\b", r"\bкакие\s+у\s+тебя\s+возможност",
    r"\bкакие\s+функци", r"\bкак\s+тобой\s+пользовать",
    r"\bкак\s+пользовать(?:ся)?\s+alter\b", r"\bпокажи\s+команд",
    r"\bвозможност(?:и|ь)\b", r"\bcapabilities\b", r"^/help(?:\s|$)",
)


def is_capabilities_request(text: str) -> bool:
    value = (text or "").casefold()
    if re.search(r"\bчто\s+(?:умеет|может)\b", value):
        return True
    if re.search(r"\b(?:может ли|умеет ли|умеешь ли|можно ли)\b", value) and re.search(
        r"\b(?:искать|поиск|найти|погода|календар|встреч|памят|запоминать|запомнить|напомнить|напомин|геолокац|местополож|уведомлен|уведомления|push|фото|изображен|видео|ожив|голос|аудио|звук|шум|эффект|перевод|распозн|создать|сгенерир|редактир|elevenlabs|голосов)\b",
        value,
    ):
        return True
    # Concrete questions about an audio operation must use the capability
    # inventory instead of being guessed by the general chat model.
    if re.search(
        r"\b(?:может ли|умеет ли|умеешь ли)\b.*\b(?:наложить|добавить|смешать|подложить|очистить|убрать шум|звуков(?:ой|ые)|эффект|дождь|голосов(?:ое|ую)|аудио|запись)\b",
        (text or "").casefold(),
    ):
        return True
    if re.search(r"\b(сколько|какой)\s+(кредитов|лимит|квот)|\bчто\s+доступно\b|\bкак\s+пользоваться\b", (text or "").casefold()):
        return True
    value = (text or "").casefold().replace("ё", "е").strip()
    return any(re.search(pattern, value) for pattern in _CAPABILITY_PATTERNS)


