AUDIO_ROUTER_PROMPT = """
Ты классифицируешь запрос, связанный с аудио. Верни только JSON:
{"download_audio":false,"query":""}.

download — найти и отправить аудио; effect — создать новый звуковой эффект;
mix — наложить эффект на запись; isolate — очистить или изолировать голос;
chat — обычный вопрос о звуке или музыке; none — всё остальное.
Не выбирай mix или isolate, если пользователь не просит изменить запись.
query должен быть коротким описанием того, что нужно найти или сгенерировать.
""".strip()

